import type { BlogPost } from "@/lib/blog-data";

export interface ValuationMetric {
  label: string;
  value: string;
  signal?: "positive" | "neutral" | "negative";
}

export interface RiskItem {
  risk: string;
  likelihood: "low" | "medium" | "high";
  impact: "low" | "medium" | "high";
}

export interface GlossaryItem {
  term: string;
  definition: string;
}

export interface VisualBlocks {
  valuationSnapshot: ValuationMetric[];
  riskMatrix: RiskItem[];
  glossary: GlossaryItem[];
  checklist: string[];
}

const GLOSSARY_POOL: GlossaryItem[] = [
  { term: "P/E", definition: "Price-to-earnings ratio; compares share price to earnings per share." },
  { term: "Dividend Yield", definition: "Annual dividend divided by share price, expressed as a percentage." },
  { term: "ROE", definition: "Return on equity; net profit relative to shareholder equity." },
  { term: "EPS", definition: "Earnings per share; net profit attributable to each outstanding share." },
  { term: "Market Cap", definition: "Total market value of a company's outstanding shares." },
  { term: "Operating Cash Flow", definition: "Cash generated by core business operations before financing." },
  { term: "Debt-to-Equity", definition: "Total debt divided by shareholders' equity." },
  { term: "Margin of Safety", definition: "Buying below estimated fair value to reduce downside risk." }
];

function parseChecklistFromMarkdown(content: string): string[] {
  const lines = content.split("\n");
  const out: string[] = [];
  let inChecklist = false;
  for (const raw of lines) {
    const line = raw.trim();
    if (line.startsWith("## ")) {
      inChecklist = line.toLowerCase().includes("checklist");
      continue;
    }
    if (!inChecklist) continue;
    if (line.startsWith("- ")) out.push(line.slice(2).trim());
    if (/^\d+\. /.test(line)) out.push(line.replace(/^\d+\. /, "").trim());
    if (out.length >= 6) break;
  }
  return out.filter(Boolean);
}

function parseRisks(content: string): RiskItem[] {
  const lines = content.split("\n");
  const risks: string[] = [];
  let inRiskSection = false;
  for (const raw of lines) {
    const line = raw.trim();
    if (line.startsWith("## ")) {
      inRiskSection = line.toLowerCase().includes("risk");
      continue;
    }
    if (!inRiskSection) continue;
    if (line.startsWith("- ")) risks.push(line.slice(2).trim());
    if (/^\d+\. /.test(line)) risks.push(line.replace(/^\d+\. /, "").trim());
    if (risks.length >= 6) break;
  }
  return risks.slice(0, 4).map((risk) => {
    const lower = risk.toLowerCase();
    const highWords = ["regulatory", "fx", "outflow", "debt", "liquidity", "macro", "volatility"];
    const mediumWords = ["execution", "competition", "delay", "demand", "rates"];
    const impact: RiskItem["impact"] = highWords.some((w) => lower.includes(w))
      ? "high"
      : mediumWords.some((w) => lower.includes(w))
        ? "medium"
        : "low";
    const likelihood: RiskItem["likelihood"] = lower.includes("ongoing") || lower.includes("persistent")
      ? "high"
      : lower.includes("possible") || lower.includes("could")
        ? "medium"
        : "low";
    return { risk, impact, likelihood };
  });
}

function parseValuationMetrics(content: string): ValuationMetric[] {
  const rows = content.split("\n").map((line) => line.trim());
  const metrics: ValuationMetric[] = [];

  const metricMatchers: Array<{ token: RegExp; label: string }> = [
    { token: /p\/e/i, label: "P/E" },
    { token: /ev\/ebitda/i, label: "EV/EBITDA" },
    { token: /div(?:idend)?\s*yield/i, label: "Dividend Yield" },
    { token: /\broe\b/i, label: "ROE" },
    { token: /market cap/i, label: "Market Cap" }
  ];

  for (const row of rows) {
    for (const matcher of metricMatchers) {
      if (!matcher.token.test(row)) continue;
      const valueMatch = row.match(/(\d+(?:\.\d+)?x|\d+(?:\.\d+)?%|KES\s*[\d,.]+(?:\s*[BM]n?)?)/i);
      const value = valueMatch ? valueMatch[1] : "Mentioned in report";
      metrics.push({ label: matcher.label, value, signal: "neutral" });
      break;
    }
    if (metrics.length >= 4) break;
  }

  if (metrics.length === 0) {
    return [
      { label: "Valuation", value: "No clean ratio extracted", signal: "neutral" },
      { label: "Earnings Trend", value: "Review latest filing", signal: "neutral" },
      { label: "Cash Flow Signal", value: "Check OCF quality", signal: "neutral" }
    ];
  }
  return metrics;
}

function parseGlossary(content: string): GlossaryItem[] {
  const lower = content.toLowerCase();
  const selected = GLOSSARY_POOL.filter((item) => lower.includes(item.term.toLowerCase()));
  if (selected.length > 0) return selected.slice(0, 6);
  return GLOSSARY_POOL.slice(0, 4);
}

function fallbackChecklist(category: BlogPost["category"]): string[] {
  if (category === "education") {
    return [
      "Define your thesis before opening a position.",
      "Set downside invalidation and position size limits.",
      "Check recent filings before acting on narrative momentum.",
      "Review portfolio concentration after each trade."
    ];
  }
  return [
    "Verify thesis against latest disclosed numbers.",
    "Stress-test downside scenarios before entry.",
    "Track upcoming filings and key macro dates."
  ];
}

export function buildVisualBlocks(post: BlogPost): VisualBlocks {
  const valuationSnapshot = post.blocks?.valuationSnapshot && post.blocks.valuationSnapshot.length > 0
    ? post.blocks.valuationSnapshot
    : parseValuationMetrics(post.content);

  const riskMatrix = post.blocks?.riskMatrix && post.blocks.riskMatrix.length > 0
    ? post.blocks.riskMatrix
    : parseRisks(post.content);

  const glossary = post.blocks?.glossary && post.blocks.glossary.length > 0
    ? post.blocks.glossary
    : parseGlossary(post.content);

  const checklist = post.blocks?.checklist && post.blocks.checklist.length > 0
    ? post.blocks.checklist
    : (() => {
        const parsed = parseChecklistFromMarkdown(post.content);
        return parsed.length > 0 ? parsed : fallbackChecklist(post.category);
      })();

  return { valuationSnapshot, riskMatrix, glossary, checklist };
}

